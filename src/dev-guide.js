// 设计文档放哪：任务路径里直接写了 .md 文件就用它，否则放在第一个路径下面
export function designDocPath(task) {
  const paths = (task.paths ?? []).map((p) => String(p).replace(/\/+$/, ''));
  const file = paths.find((p) => p.toLowerCase().endsWith('.md'));
  if (file) return file;
  return paths[0] ? `${paths[0]}/${task.id}-设计.md` : `${task.id}-设计.md`;
}

const designTemplate = (task) => `# ${task.id} 设计：${task.title}

## 1. 目标和范围
这次要做什么、明确不做什么（引用需求说明或产品文档的原话）。

## 2. 现状
相关的现有模块：入口在哪、调用怎么走、数据存在哪，写出文件路径。项目里有同类功能的，写出是哪几个文件，这次照它的哪种写法。

## 3. 技术选型
沿用现有技术栈的写「沿用现有：<语言、框架、构建、部署>」。
新项目或要引入新框架 / 语言 / 数据库 / 主要依赖 / 构建或部署方式的，写：
- 现有约束：项目已有的语言、框架、构建和部署方式，团队已有的代码和习惯
- 候选（2–3 个）：各自的优缺点；怎么融合进现有项目（要改哪些、对构建和部署的影响、上手成本）
- 推荐和理由
- 用户确认：<用户的决定原话>（等用户答复后填）

## 4. 实现思路
难点在哪、怎么做；考虑过的其他做法和不选的原因（至少写一种）。

## 5. 文件清单
| 文件 | 新建 / 修改 | 所在层 | 职责（一句话） |
|---|---|---|---|

## 6. 接口
模块之间的函数或类：名字、参数、返回值、出错时怎么办。
前后端接口：路径、方法、请求、响应、错误码，原样写出，前后端照抄。

## 7. 数据结构
新增或改动的表、字段、配置：名字、类型、单位、取值范围、默认值，和已有字段的关系。

## 8. 调用流程
主流程一步一步写：用户操作 → 哪个文件的哪个函数 → …… → 返回什么。出错和边界情况怎么走。

## 9. 复用和共用
复用哪些已有的函数、组件、工具（写出路径）；新增的共用代码放在哪。

## 10. 拆卡建议
拆成几张开发卡：每张的角色、改哪些文件、依赖哪张、哪些可以并行。入口文件、路由表、汇总导出、共享类型这类共用文件只放进一张卡。

## 11. 待确认
没想清楚、需要用户或产品确认的问题。没有就写「无」。
`;

