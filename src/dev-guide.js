const isRole = (re) => (role) => re.test(String(role ?? '').trim());
export const isProductRole = isRole(/^(product|pm|产品)$/i);
const isFrontendRole = isRole(/^(frontend|fe|web|前端)$/i);
const isBackendRole = isRole(/^(backend|be|server|后端)$/i);

const FRONTEND = [
  '',
  '**前端**',
  '- **分层**：页面、组件、数据请求、状态分开放。组件只管展示和交互，取数据和展示分开；接口调用集中在一处，不在组件里到处写请求。一个组件超过 200 行就拆；属性往下传超过 3 层，改结构或用上下文。',
  '- **沿用设计系统**：用项目已有的组件、颜色和间距变量、字号层级，不写裸色值和随手的像素值，不另起一套样式。',
  '- **各种状态一起做完**：加载中、空数据、出错、无权限、禁用、窄屏都是功能的一部分，不留到最后。出错时告诉用户原因和下一步；状态不只靠颜色区分（配文字或图标）。',
  '- **布局自己说话**：最重要的信息和操作放在第一眼的位置，视觉权重跟着用户最主要的操作走。不加能靠布局看懂的说明文字。',
  '- **不要「AI 味」的界面**：紫色或靛蓝渐变、处处大圆角、到处一样大的留白、千篇一律的卡片网格、层层阴影、和内容无关的大横幅，这些都不要；用项目自己的配色和间距，用接近真实的内容排版（长文本、换行、溢出要能看出问题）。',
];

const BACKEND = [
  '',
  '**后端**',
  '- **分层**：接口层只做参数校验和调用，业务逻辑放在服务层，数据读写放在数据层，不在接口层里直接写查询，不跨层调用。',
  '- **和已有接口一致**：路径用名词不用动词（`/api/tasks`，不是 `/api/getTasks`）；字段命名、日期格式、分页方式、错误结构都照已有接口写。同一个接口不管什么条件都返回同样的结构；列表接口要分页。',
  '- **错误语义统一**：HTTP 状态码语义正确，出错不返回 200；错误带稳定的错误码和人能看懂的原因，不吞掉异常，不把内部堆栈、数据库细节漏给调用方。',
  '- **接口兼容**：接口格式以卡上的约定为准。新增可选字段是安全的；删除、改名、改类型、把可选改成必填都会弄坏前端，要先 `ateam ask`。返回里暴露出去的东西都会有人依赖，只返回需要的。',
  '- **校验放在边界**：用户输入、外部接口的返回、配置要校验（外部接口的返回当成不可信数据）；内部函数之间不重复做防御性检查。',
  '- **写操作能安全重试**：重复提交不会多建一条、多扣一次。防重复靠唯一约束一步完成，「先查有没有、再插入」是竞态，不算防住。',
];

// 你可能会这样想 → 实际上（agent 最常见的偷懒理由，直接堵住）
const EXCUSES = [
  '',
  '**这些想法出现时停一下**',
  '- 「先写在一个文件里跑通，以后再拆」→ 以后不会有人拆。现在就按职责拆。',
  '- 「项目里没有现成的，我自己写一个」→ 先搜过再说。名字不同、作用相同的函数，是多人轮流写同一个项目最常见的问题。',
  '- 「顺手把旁边这段也改了」→ 写进「发现但没做」，交给 leader。',
  '- 「以后可能要支持别的情况，先抽象一下」→ 等第三次真的用到再抽。',
  '- 「建个 utils / helpers / common 放一下」→ 按它做的事命名、放到用它的模块里；杂物文件会越堆越大。',
  '- 「这里加个 if 处理一下特殊情况」→ 往不相关的流程里硬塞分支是结构问题；同一种判断到处出现，说明缺了一个模型。',
];

export function devGuide(agentId, role, full) {
  if (!full) {
    return ['', '改的时候同样遵守开发规范：只修修改意见列出的问题，不加新功能、不顺手重构；提交前逐行看一遍 diff，在提交说明里附上最终的文件清单。'];
  }
  return [
    '',
    '## 开发规范（这张卡必须遵守）',
    '',
    '**动手前**',
    '1. **逐字读卡**：任务描述里的动词就是范围。说「修复」就只修复，不「改进」；说「加一个按钮」就加按钮，不重新设计整个表单。描述能有两种理解时先 `ateam ask`，不要按更大的理解去做。',
    '2. **先读再写**：读这张卡涉及的现有代码和项目文档（项目规则里提到的规范文件一定要读），弄清楚入口、调用路径、新代码该放在哪一层和哪个目录。**找到项目里同类的东西是怎么写的**（同类页面、同类接口、同类数据访问），照着它的写法来。要写辅助函数之前先搜一下有没有现成的，不要给已有的功能再写一个名字差不多的第二份实现。',
    `3. **先报方案**：用 \`ateam progress --as ${agentId} "方案：..."\` 报一份几行的方案：新建和修改哪些文件、每个文件负责什么、放在哪一层、对外的函数或接口是什么、为什么这样拆。先想「最简单能工作的做法是什么」。报完直接开始写，不用等批准；写的过程中方案有大的改变，再报一次。`,
    '',
    '**写代码时**',
    '4. **按职责拆文件**：一个文件只负责一件事，不把整个功能写进一个文件；沿用项目已有的目录结构、分层、命名和错误处理方式，不在目录根下平铺。功能专属的逻辑放在它自己的模块里，不塞进共用模块。项目规定了文件或函数的行数上限就遵守；没有规定时，文件到几百行、函数超过一屏就该拆。',
    '5. **一小段一小段写**：先写最小的一段能编译的完整功能，编译通过再写下一段，不要攒几百行再一起编译。每段只做一件事，项目始终保持能编译。',
    '6. **简单直接**：先写最直白、明显正确的版本。能提前返回就不嵌套，嵌套不超过 3 层；名字按它在业务里的意思起，不用 `data`、`temp`、`result` 这种没信息的名字。',
    '7. **不重复，也不过度设计**：同一段业务逻辑不复制第二份，抽到共用的地方；但不为「以后可能用到」加抽象层、配置项、扩展点，每加一层都要说得出现在就需要的理由。先用项目已有的依赖和标准库，要引入新依赖先 `ateam ask`。',
    '8. **只改任务要求的**：不顺手重构、不改格式、不给没改的代码加注释或类型。确定没用的代码就干净地删掉，不留 `// removed` 注释，不改名成 `_old` 留着。发现范围外值得改的问题，记下来写进提交说明，交给 leader 另派卡。',
    '9. **容易藏 bug 的地方多看一眼**：默认值和回退（`??`、`||`、`or`）检查哪一边才是兜底；带单位的值（分和元、毫秒和秒、0–1 和百分比）在产生它的地方确认单位，用的地方按同一个单位算，不靠变量名猜；名字很像的字段（单复数、新旧字段名）确认是同一个东西；异步或事件处理里读到的记录，确认一定已经被创建，不靠「通常先执行」。',
    '',
    '**提交前**',
    '10. **逐行看 diff**：每一行问自己「这一行是这张卡要求的吗」「能不能用更少的代码做到」，不是就删掉；对照第 4、7 条检查文件和函数的大小、有没有重复代码。',
    '11. **提交说明**写三样：最终的文件清单（每个文件一句话说明职责）；和方案不一样的地方及原因；「发现但没做」的范围外问题。',
    ...(isFrontendRole(role) ? FRONTEND : isBackendRole(role) ? BACKEND : []),
    ...EXCUSES,
  ];
}
